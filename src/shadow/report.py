"""Score shadow mode and render the report (the only step that reads labels).

Inputs: the lead's blind handling (Step A), the lead's review of the agent's drafts (Step B), the second reviewer's ratings, the gated 7B run's
``score.json`` (the agent's per-ticket results) and the held-out labels. Outputs: a summary dictionary and the markdown report.

No pass or miss is applied (phase-4-design-and-acceptance.md section 6.2); every figure is described with its count and interval.
"""
import statistics

from src.baseline import scoring
from src.baseline.report import pct, ratio
from src.baseline.scoring import time_stats

ACCEPTED = ("accept", "minor_edit")
TRAINED_HANDLER_MEDIAN_S = 103          # last-third median of the dev baseline (baseline-report.md); the "trained handler" comparator
BASELINE_MEAN_S, BASELINE_MEDIAN_S = 162, 136


def agent_rows(score: dict, ids: list) -> dict:
    by_id = {r["ticket_id"]: r for r in score["rows"]}
    out = {}
    for tid in ids:
        r = by_id[tid]
        out[tid] = {"category_ok": bool(r["category_ok"]), "escalation_ok": bool(r["escalated"]) == bool(r["label_escalate"]),
                    "action_ok": r["action"] == r["expected_action"], "action": r["action"], "expected_action": r["expected_action"]}
    return out


def summarise_shadow(sample: dict, manual: list, review: list, ratings: list, labels_by_id: dict, score: dict) -> dict:
    ids = sample["ticket_ids"]
    handled, reviewed = {r["ticket_id"] for r in manual if not r["practice"]}, {r["ticket_id"] for r in review}
    if handled != set(ids) or reviewed != set(ids):
        raise ValueError("Step A and Step B must both cover all sample tickets before reporting")
    agent = agent_rows(score, ids)
    man = scoring.summarise(manual, labels_by_id)
    man_secs = {r["ticket_id"]: r["seconds"] for r in manual}
    rev_secs = {r["ticket_id"]: r["seconds"] for r in review}
    outcomes = {o: sum(r["outcome"] == o for r in review) for o in ("accept", "minor_edit", "major_edit", "reject")}
    accepted = [r for r in review if r["outcome"] in ACCEPTED]
    approved_errors = sorted(r["ticket_id"] for r in accepted if not agent[r["ticket_id"]]["action_ok"])
    overruled_correct = sorted(r["ticket_id"] for r in review if r["outcome"] not in ACCEPTED and agent[r["ticket_id"]]["action_ok"])

    def final_ok(r):
        if r["outcome"] in ACCEPTED:
            return agent[r["ticket_id"]]["action_ok"]
        return set(r["replacement_actions"] or ()) == set(labels_by_id[r["ticket_id"]]["expected_actions"])
    finals = [final_ok(r) for r in review]
    ratios = [rev_secs[t] / man_secs[t] for t in ids if man_secs[t] > 0]
    rated = {r["ticket_id"]: r for r in ratings}
    lead_accept = {r["ticket_id"]: r["outcome"] in ACCEPTED for r in review}
    rater = None
    if rated:
        agree = sum(rated[t]["overall_ok"] == lead_accept[t] for t in rated)
        rater = {"n": len(rated), "raters": sorted({r["rater"] for r in ratings}), "agree": agree,
                 "items": {k: sum(r[k] for r in rated.values()) for k in ("correct_action", "policy_safe", "grounded", "tone", "overall_ok")},
                 "disagreements": sorted(t for t in rated if rated[t]["overall_ok"] != lead_accept[t])}
    return {
        "n": len(ids), "manual": man, "manual_seconds": man["time"], "review_seconds": time_stats(list(rev_secs.values())),
        "review_vs_manual_median_ratio": statistics.median(ratios), "outcomes": outcomes,
        "accepted": len(accepted), "approved_errors": approved_errors, "overruled_correct": overruled_correct,
        "final_ok": sum(finals), "agent": {k: sum(a[k] for a in agent.values()) for k in ("category_ok", "escalation_ok", "action_ok")},
        "manual_counts": man["counts"], "rater": rater, "gap_hours": sorted({r.get("gap_hours") for r in review}, key=lambda x: (x is None, x)),
        "lookups_review": sum(sum(r["lookups"].values()) for r in review),
        "disagreements": [t for t in ids if (not agent[t]["action_ok"]) or any(r["ticket_id"] == t and not r["actions_ok"] for r in man["disagreements"])],
    }


def render(summary: dict, sample: dict, run_id: str, date: str) -> str:
    n, m, rv, o = summary["n"], summary["manual_seconds"], summary["review_seconds"], summary["outcomes"]
    mc, ag = summary["manual_counts"], summary["agent"]
    lines = ["# Phase 4 Shadow-mode Report", "",
             f"Generated by `python -m src.shadow report` on {date}. Method: `phase-4-design-and-acceptance.md` section 6; procedure: `phase-4-shadow-runbook.md`.", "",
             "| | |", "|---|---|", f"| Sample | {n} held-out tickets, seed {sample['seed']}, stratified by scenario |",
             f"| Agent run | `{run_id}` (qwen2.5:7b, the single gated held-out run) |", "| Handler | one person (the project lead), the same as the baseline |",
             f"| Gap between Step A and Step B | {', '.join(str(g) if g is not None else 'not recorded' for g in summary['gap_hours'])} hours |", "",
             "No pass or miss is applied to these figures. With n = 40 every interval is wide.", "",
             "## 1. Time", "", "| Seconds per ticket | Mean | Median | 90th percentile | Fastest | Slowest |", "|---|---|---|---|---|---|"]
    for name, t in (("Step A: handled by hand, blind (held-out)", m), ("Step B: reviewing the agent's draft", rv)):
        lines.append(f"| {name} | {t['mean']:.0f} | {t['median']:.0f} | {t['p90']:.0f} | {t['min']:.0f} | {t['max']:.0f} |")
    lines += ["", f"Paired by ticket, the review took a median of {summary['review_vs_manual_median_ratio']:.2f} times the manual time.", "",
              "| Comparator | Median seconds | Review time as a share of it |", "|---|---|---|"]
    for name, base in (("Step A, this sample", m["median"]), ("Dev baseline, all 40 tickets", BASELINE_MEDIAN_S),
                       ("Dev baseline, trained handler (last third)", TRAINED_HANDLER_MEDIAN_S)):
        lines.append(f"| {name} | {base:.0f} | {pct(rv['median'] / base)} |")
    lines += ["", "## 2. What the reviewer did with the drafts", "", "| Outcome | Tickets |", "|---|---|"]
    lines += [f"| {label} | {o[key]} |" for key, label in (("accept", "Accepted as is"), ("minor_edit", "Accepted with a minor edit"),
                                                          ("major_edit", "Major edit"), ("reject", "Rejected"))]
    lines += ["", f"Accepted as is or with a minor edit: {ratio(summary['accepted'], n)}.", "",
              "### Safety of the review", "",
              f"- **Approved errors** (draft accepted although its action differs from the label): {len(summary['approved_errors'])}"
              + (f" ({', '.join(summary['approved_errors'])})" if summary['approved_errors'] else "") + ". This is the cost of trusting the draft.",
              f"- **Correct drafts overruled** (edited or rejected although the action matched the label): {len(summary['overruled_correct'])}"
              + (f" ({', '.join(summary['overruled_correct'])})" if summary['overruled_correct'] else "") + ".",
              f"- **Final action correct after review** (accepted drafts count by the agent's action; edits and rejects by the action the reviewer gave): {ratio(summary['final_ok'], n)}.",
              "", "## 3. Quality on the same tickets", "",
              "| Measure | Handled by hand (Step A) | Agent alone (7B) |", "|---|---|---|",
              f"| Category correct | {ratio(mc['category_ok']['correct'], n)} | {ratio(ag['category_ok'], n)} |",
              f"| Escalation decision correct | {ratio(mc['escalate_ok']['correct'], n)} | {ratio(ag['escalation_ok'], n)} |",
              f"| Action correct | {ratio(mc['actions_ok']['correct'], n)} (set exactly right) | {ratio(ag['action_ok'], n)} (action equals the label's) |",
              "", "The two action measures are close but not identical: the person names a set of actions, the agent one action, and a safe hand-over to a person counts as wrong for the agent when the label expected an answer.", ""]
    r = summary["rater"]
    lines += ["## 4. Second reviewer", ""]
    if r:
        lines += [f"{', '.join(r['raters'])} rated {r['n']} drafts blind to the lead's decisions.", "", "| Question | Yes |", "|---|---|"]
        lines += [f"| {label} | {ratio(r['items'][key], r['n'])} |" for key, label in (("correct_action", "Right action"), ("policy_safe", "Safe under policy"),
                                                                                         ("grounded", "Grounded in the records"), ("tone", "Content to send as written"),
                                                                                         ("overall_ok", "All four"))]
        lines += ["", f"The reviewer's overall verdict agreed with the lead's accept or overrule on {r['agree']} of {r['n']} drafts"
                  + (f" (disagreements: {', '.join(r['disagreements'])})." if r['disagreements'] else ".")]
    else:
        lines += ["No second reviewer took part. The lead's own review is the only judgement of draft quality, and the lead knows the system. This limits what can be said about reply quality."]
    lines += ["", "## 5. Limits", "",
              "- One handler, who is also the author of the system. The baseline showed a learning effect (first-third median 237 s, last-third 103 s), so two dev-baseline comparators are shown.",
              "- Reviewing is faster than writing and the reviewer knows what the agent tends to do; a new support agent would probably take longer.",
              "- The terminal tool is faster than switching between real systems, in both steps.",
              "- Step B includes the time to give the action and reply for an edit or a reject, so a rejected draft costs about what handling it by hand costs.",
              f"- {n} tickets: describe, do not test. The 25 tickets outside the agent's scope (Set B) are included in proportion, so the acceptance rate is lower than on in-scope tickets alone.", ""]
    return "\n".join(lines)